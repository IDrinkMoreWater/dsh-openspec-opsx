/**
 * dsh-openspec-opsx — OpenSpec spec-driven workflows for DeepSeek Harness.
 *
 * Mounts two surfaces from the bundled OpenSpec payload:
 *
 *   1. Skills — `openspec-*`, model- and user-invocable, so the model can load
 *      the workflow it needs on its own.
 *   2. Slash commands — `/opsx-<id>`, which inject the matching workflow prompt
 *      as a durable user message and append whatever arguments the user typed.
 *
 * Every command declares `input.hint`. DSH puts a command on the composer's
 * "leading claim" path only when that object exists: without it the composer
 * refuses to highlight the token and executes the command immediately on a menu
 * pick, leaving no room for arguments.
 *
 * The skill and command bodies are generated by OpenSpec's own `openspec init`
 * (`--tools claude`) and committed verbatim under `skills/` and `commands/`.
 */
import { readFileSync, readdirSync } from 'node:fs'
import { randomUUID } from 'node:crypto'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

/** Plugin identity shown in loader diagnostics. */
export const name = 'dsh-openspec-opsx'
/** Both registries must exist before this plugin activates. */
export const inject = ['skills', 'commands']

const ROOT = dirname(fileURLToPath(import.meta.url))
const SOURCE = 'openspec-opsx'
/** Placeholder the composer shows while it waits for command arguments. */
const HINT = '<需求或想法 / what to build>'

/**
 * Deep-freeze a value in place.
 *
 * The host's own `createUserMessage` freezes with `deepFreeze(structuredClone(x))`;
 * mirroring it keeps the injected message immutable the same way without importing
 * `@deepseek-ai/dsh-llm`, which a plugin installed outside the profile cannot resolve.
 *
 * @template T
 * @param {T} value
 * @returns {T}
 */
function deepFreeze(value) {
	if (value !== null && typeof value === 'object' && !Object.isFrozen(value)) {
		Object.freeze(value)
		for (const key of Object.keys(value)) deepFreeze(value[key])
	}
	return value
}

/**
 * Build the durable user message a command injects.
 *
 * Structurally identical to the host helper: user role, fresh identity, frozen.
 *
 * @param {{ content: Array<object>, source: object }} input
 * @returns {object}
 */
function createUserMessage(input) {
	return deepFreeze(structuredClone({ ...input, role: 'user', id: randomUUID() }))
}

/**
 * Split one YAML frontmatter block from its body.
 *
 * The generated files use flat `key: value` scalars only, so a full YAML parser
 * would be dead weight here.
 *
 * @param {string} text - Whole file contents.
 * @returns {{ data: Record<string, string>, body: string }}
 */
function splitFrontmatter(text) {
	if (!text.startsWith('---')) return { data: {}, body: text }
	const end = text.indexOf('\n---', 3)
	if (end === -1) return { data: {}, body: text }
	const data = {}
	for (const line of text.slice(3, end).split(/\r?\n/)) {
		const match = /^([A-Za-z0-9_-]+):\s*(.*)$/.exec(line)
		if (match === null) continue
		const value = match[2].trim().replace(/^["']|["']$/g, '')
		if (value !== '') data[match[1]] = value
	}
	return { data, body: text.slice(end + 4).replace(/^\s*\n/, '') }
}

/**
 * Read the bundled skills.
 *
 * @returns {Array<{ name: string, description: string, content: string }>}
 */
function loadSkills() {
	const root = join(ROOT, 'skills')
	const skills = []
	for (const entry of readdirSync(root, { withFileTypes: true })) {
		if (!entry.isDirectory()) continue
		const { data, body } = splitFrontmatter(readFileSync(join(root, entry.name, 'SKILL.md'), 'utf8'))
		const skillName = (data.name ?? entry.name).trim()
		if (skillName === '' || body === '') throw new Error(`dsh-openspec-opsx: skill "${entry.name}" is empty`)
		skills.push({
			name: skillName,
			description: (data.description ?? skillName).trim(),
			content: body,
		})
	}
	return skills
}

/**
 * Read the bundled slash-command prompts.
 *
 * @returns {Array<{ name: string, description: string, content: string }>}
 */
function loadCommands() {
	const root = join(ROOT, 'commands')
	return readdirSync(root)
		.filter((file) => file.endsWith('.md'))
		.sort()
		.map((file) => {
			const id = file.slice(0, -3)
			const { data, body } = splitFrontmatter(readFileSync(join(root, file), 'utf8'))
			if (body === '') throw new Error(`dsh-openspec-opsx: command "${file}" is empty`)
			return {
				name: `opsx-${id}`,
				description: (data.description ?? `Run the OpenSpec ${id} workflow`).trim(),
				content: body,
			}
		})
}

/**
 * Inject one workflow prompt, appending the user's arguments when present.
 *
 * @param {import('@deepseek-ai/dsh-commands').CommandInvocation} invocation
 * @param {{ name: string, content: string }} command
 * @returns {{ kind: 'success', text: string }}
 */
function runCommand(invocation, command) {
	const args = (invocation.rawInput ?? '').trim()
	const text = args === '' ? command.content : `${command.content}\n\n---\n\n## 用户输入\n\n${args}`
	invocation.agent.followup(
		createUserMessage({
			content: [{ type: 'text', text }],
			source: { kind: 'skill-invocation', name: command.name, form: 'instructions' },
		}),
	)
	return { kind: 'success', text: `Loaded ${command.name}.` }
}

/**
 * Register the bundled skills and slash commands on the host plane.
 *
 * @param {import('cordis').Context} ctx
 */
export function apply(ctx) {
	for (const skill of loadSkills()) {
		ctx.skills.register({
			name: skill.name,
			description: skill.description,
			content: skill.content,
			source: SOURCE,
			invocation: { modelInvocable: true, userInvocable: true },
		})
	}
	for (const command of loadCommands()) {
		ctx.commands.register({
			name: command.name,
			description: command.description,
			input: { hint: HINT },
			handler: (invocation) => runCommand(invocation, command),
		})
	}
}
